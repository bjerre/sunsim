#!/usr/bin/env python3
"""Generate the compile-time installation tables from config/installation.json."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
DOCUMENT = ROOT / "config" / "installation.json"
LAYOUT_OUTPUT = ROOT / "components" / "sunsim_events" / "src" / "layout.generated.inc"
INSTALLATION_OUTPUT = ROOT / "components" / "sunsim_events" / "src" / "installation.generated.inc"

GROUPS = {
    "Wall": ("Wall", "ColorBulb"),
    "Work": ("Work", "ColorBulb"),
    "Desk": ("Desk", "Plug"),
    "Grow": ("Grow", "Plug"),
    "Button": ("Button", "Button"),
}
KINDS = {"color-bulb": "ColorBulb", "plug": "Plug", "button": "Button"}
MODES = {
    "daylight": "Daylight",
    "off": "Off",
    "red-alert": "RedAlert",
    "tuning": "Tuning",
}
SETTINGS = {
    "active": "active",
    "active_days": "active_days",
    "fade": "fade",
    "work": "work",
    "work_cool_mireds": "work_cool_mireds",
    "work_warm_mireds": "work_warm_mireds",
}
HEADER = "// Generated by tools/generate_installation.py from config/installation.json. Do not edit.\n"


class DocumentError(ValueError):
    pass


def require_object(value: Any, context: str) -> dict[str, Any]:
    if not isinstance(value, dict):
        raise DocumentError(f"{context} must be an object")
    return value


def require_list(value: Any, context: str) -> list[Any]:
    if not isinstance(value, list):
        raise DocumentError(f"{context} must be an array")
    return value


def require_keys(value: dict[str, Any], required: set[str], optional: set[str], context: str) -> None:
    missing = required - value.keys()
    unknown = value.keys() - required - optional
    if missing:
        raise DocumentError(f"{context} is missing: {', '.join(sorted(missing))}")
    if unknown:
        raise DocumentError(f"{context} has unknown fields: {', '.join(sorted(unknown))}")


def quoted(value: str) -> str:
    return json.dumps(value)


def time_minutes(value: Any, context: str) -> int:
    if not isinstance(value, str) or len(value) != 5 or value[2] != ":":
        raise DocumentError(f"{context} must be a time in HH:MM format")
    if value == "24:00":
        return 24 * 60
    try:
        hour, minute = (int(part) for part in value.split(":"))
    except ValueError as error:
        raise DocumentError(f"{context} must be a time in HH:MM format") from error
    if not 0 <= hour < 24 or not 0 <= minute < 60:
        raise DocumentError(f"{context} is outside the 24-hour day")
    return hour * 60 + minute


def setting_or_value(value: Any, context: str, literal: str) -> str:
    value = require_object(value, context)
    require_keys(value, set(), {"setting", "value"}, context)
    if ("setting" in value) == ("value" in value):
        raise DocumentError(f"{context} needs exactly one of 'setting' or 'value'")
    if "setting" in value:
        name = value["setting"]
        if not isinstance(name, str):
            raise DocumentError(f"{context}.setting must be a string")
        if name not in SETTINGS:
            raise DocumentError(f"{context} names unknown setting {name!r}")
        return f"&ProgramConfig::{SETTINGS[name]}"
    return literal(value["value"], context)


def day_span(value: Any, context: str) -> str:
    value = require_object(value, context)
    require_keys(value, {"start", "end"}, set(), context)
    start = time_minutes(value["start"], f"{context}.start")
    end = time_minutes(value["end"], f"{context}.end")
    if start >= end:
        raise DocumentError(f"{context}.start must be before {context}.end")
    return f"DaySpan{{std::chrono::minutes{{{start}}}, std::chrono::minutes{{{end}}}}}"


def week_days(value: Any, context: str) -> str:
    value = require_object(value, context)
    require_keys(value, set(), {"setting", "value"}, context)
    if ("setting" in value) == ("value" in value):
        raise DocumentError(f"{context} needs exactly one of 'setting' or 'value'")
    if "setting" in value:
        name = value["setting"]
        if not isinstance(name, str) or name != "active_days":
            raise DocumentError(f"{context} names unsupported setting {name!r}")
        return "&ProgramConfig::active_days"
    days = value["value"]
    if days == "every-day":
        return "kEveryDay"
    if days == "weekdays":
        return "kMondayToFriday"
    raise DocumentError(f"{context}.value must be 'every-day' or 'weekdays'")


def duration(value: Any, context: str) -> str:
    if not isinstance(value, int) or isinstance(value, bool) or value < 0 or value > 1440:
        raise DocumentError(f"{context} must be an integer from 0 to 1440")
    return f"std::chrono::minutes{{{value}}}"


def emit_hours(value: Any, context: str) -> str:
    value = require_object(value, context)
    if "setting" in value:
        require_keys(value, {"setting"}, set(), context)
        name = value["setting"]
        if not isinstance(name, str) or name not in {"active", "work"}:
            raise DocumentError(f"{context} names unsupported schedule setting {name!r}")
        return f"&ProgramConfig::{name}"
    return day_span(value, context)


def emit_window(value: dict[str, Any], context: str) -> str:
    require_keys(value, {"type", "hours"}, {"days", "fadeMinutes"}, context)
    hours = emit_hours(value["hours"], f"{context}.hours")
    days = week_days(value.get("days", {"value": "every-day"}), f"{context}.days")
    fade = setting_or_value(
        value.get("fadeMinutes", {"value": 0}),
        f"{context}.fadeMinutes",
        duration,
    )
    return f"Window{{.hours = {hours}, .days = {days}, .fade = {fade}}}"


def emit_gate(value: Any, context: str) -> str:
    rules = require_list(value, context)
    if not 1 <= len(rules) <= 4:
        raise DocumentError(f"{context} must contain 1 to 4 rules")
    emitted = []
    for index, item in enumerate(rules):
        rule_context = f"{context}[{index}]"
        item = require_object(item, rule_context)
        kind = item.get("type")
        if kind == "always":
            require_keys(item, {"type"}, set(), rule_context)
            emitted.append("Always{}")
        elif kind == "window":
            emitted.append(emit_window(item, rule_context))
        else:
            raise DocumentError(f"{rule_context}.type must be 'always' or 'window'")
    return "{" + ", ".join(emitted) + "}"


def emit_look(value: Any, context: str) -> str:
    value = require_object(value, context)
    kind = value.get("type")
    if kind == "sun-curve":
        require_keys(value, {"type"}, set(), context)
        return "SunCurve{}"
    if kind == "on-off":
        require_keys(value, {"type"}, set(), context)
        return "OnOffOnly{}"
    if kind == "work-curve":
        require_keys(value, {"type"}, {"hours", "coolMireds", "warmMireds"}, context)
        hours = emit_hours(value.get("hours", {"setting": "work"}), f"{context}.hours")

        def mireds(setting: str, field: str) -> str:
            return setting_or_value(
                value.get(field, {"setting": setting}),
                f"{context}.{field}",
                lambda number, field_context: integer(number, field_context, 1, 1000),
            )

        cool = mireds("work_cool_mireds", "coolMireds")
        warm = mireds("work_warm_mireds", "warmMireds")
        return f"WorkCurve{{.hours = {hours}, .cool = {cool}, .warm = {warm}}}"
    raise DocumentError(f"{context}.type is not a supported look")


def integer(value: Any, context: str, low: int, high: int) -> str:
    if not isinstance(value, int) or isinstance(value, bool) or not low <= value <= high:
        raise DocumentError(f"{context} must be an integer from {low} to {high}")
    return str(value)


def expand_selection(selection: Any, groups: dict[str, dict[str, Any]], context: str) -> list[str]:
    if not isinstance(selection, str):
        raise DocumentError(f"{context} must be a group or role name")
    for name, group in groups.items():
        count = group["count"]
        if selection == name:
            return [f"{name}{chr(ord('A') + index)}" for index in range(count)] if count > 1 else [name]
        if count > 1 and len(selection) == len(name) + 1 and selection.startswith(name):
            suffix = selection[-1]
            if "A" <= suffix <= "Z" and ord(suffix) - ord("A") < count:
                return [selection]
    raise DocumentError(f"{context} names no group or role: {selection!r}")


def validate_document(document: Any) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    document = require_object(document, "document")
    require_keys(document, {"schemaVersion", "groups", "zones"}, set(), "document")
    if (
        not isinstance(document["schemaVersion"], int)
        or isinstance(document["schemaVersion"], bool)
        or document["schemaVersion"] != 1
    ):
        raise DocumentError("schemaVersion must be 1")

    groups = require_list(document["groups"], "groups")
    if len(groups) != len(GROUPS):
        raise DocumentError(f"groups must define exactly: {', '.join(GROUPS)}")
    by_name: dict[str, dict[str, Any]] = {}
    generated_groups = []
    for index, group in enumerate(groups):
        context = f"groups[{index}]"
        group = require_object(group, context)
        require_keys(group, {"name", "kind", "count"}, set(), context)
        name = group["name"]
        if not isinstance(name, str) or name not in GROUPS or name in by_name:
            raise DocumentError(f"{context}.name must be a unique known group")
        expected_name, expected_kind = GROUPS[name]
        kind = group["kind"]
        if not isinstance(kind, str) or kind not in KINDS or KINDS[kind] != expected_kind:
            raise DocumentError(f"{context}.kind does not match the device kind for {name}")
        count = group["count"]
        if not isinstance(count, int) or isinstance(count, bool) or not 1 <= count <= 26:
            raise DocumentError(f"{context}.count must be an integer from 1 to 26")
        by_name[name] = group
        generated_groups.append(f'GroupSpec{{Group::{expected_name}, {quoted(name)}, Kind::{expected_kind}, {count}}}')
    if list(by_name) != list(GROUPS):
        raise DocumentError("groups must appear in the Group enum order")
    role_count = sum(group["count"] for group in groups)
    if role_count > 16:
        raise DocumentError("groups exceed the firmware's 16-role persistence limit")
    if by_name["Button"]["count"] != 1:
        raise DocumentError("the current Zigbee adapter supports exactly one button")

    zones = require_list(document["zones"], "zones")
    if not 1 <= len(zones) <= 255:
        raise DocumentError("zones must contain 1 to 255 entries")
    used_roles: set[str] = set()
    zone_names: set[str] = set()
    generated_zones: list[str] = []
    for index, zone in enumerate(zones):
        context = f"zones[{index}]"
        zone = require_object(zone, context)
        require_keys(zone, {"name", "lights", "gate"}, {"modes", "controls", "weather"}, context)
        name = zone["name"]
        if not isinstance(name, str) or not name or name in zone_names:
            raise DocumentError(f"{context}.name must be a non-empty unique string")
        zone_names.add(name)

        lights = require_list(zone["lights"], f"{context}.lights")
        if not lights:
            raise DocumentError(f"{context}.lights must not be empty")
        emitted_lights = []
        zone_roles: set[str] = set()
        for light_index, light in enumerate(lights):
            light_context = f"{context}.lights[{light_index}]"
            light = require_object(light, light_context)
            require_keys(light, {"selection", "look"}, {"peakPercent"}, light_context)
            selected = expand_selection(light["selection"], by_name, f"{light_context}.selection")
            look = emit_look(light["look"], f"{light_context}.look")
            peak = integer(light.get("peakPercent", 100), f"{light_context}.peakPercent", 1, 100)
            for role in selected:
                group_name = role.rstrip("ABCDEFGHIJKLMNOPQRSTUVWXYZ")
                group = by_name[group_name]
                if group["kind"] == "button":
                    raise DocumentError(f"{light_context} selects a button")
                if look == "OnOffOnly{}" and group["kind"] != "plug":
                    raise DocumentError(f"{light_context} uses on-off look on a non-plug")
                if role in used_roles:
                    raise DocumentError(f"light {role} appears in more than one zone/look")
                used_roles.add(role)
                zone_roles.add(role)
            emitted_lights.append(
                f"Shows{{.lights = {quoted(light['selection'])}, .look = {look}, .peak = {peak}}}"
            )

        modes = require_list(zone.get("modes", ["daylight", "off", "red-alert", "tuning"]), f"{context}.modes")
        if (
            not modes
            or any(not isinstance(mode, str) or mode not in MODES for mode in modes)
            or len(set(modes)) != len(modes)
        ):
            raise DocumentError(f"{context}.modes must contain unique supported modes")
        if "daylight" not in modes:
            raise DocumentError(f"{context}.modes must include daylight")
        emitted_modes = ", ".join(f"Mode::{MODES[mode]}" for mode in modes)

        emitted_controls = []
        controls = require_list(zone.get("controls", []), f"{context}.controls")
        for control_index, control in enumerate(controls):
            control_context = f"{context}.controls[{control_index}]"
            control = require_object(control, control_context)
            require_keys(control, {"button", "single", "double", "hold"}, set(), control_context)
            button_roles = expand_selection(control["button"], by_name, f"{control_context}.button")
            if len(button_roles) != 1 or by_name["Button"]["kind"] != "button" or button_roles[0] != "Button":
                raise DocumentError(f"{control_context}.button must select the Button role")
            controls_cpp = []
            for field, mode_key in (("single", "single"), ("double", "twice"), ("hold", "hold")):
                mode = control[field]
                if mode is not None and (not isinstance(mode, str) or mode not in MODES):
                    raise DocumentError(f"{control_context}.{field} names an unsupported mode")
                if mode is not None and mode not in modes:
                    raise DocumentError(f"{control_context}.{field} selects a mode unavailable in this zone")
                expression = f"Mode::{MODES[mode]}" if mode is not None else "std::nullopt"
                controls_cpp.append(f".{mode_key} = {expression}")
            emitted_controls.append(
                f"Controls{{.by = {quoted(control['button'])}, {', '.join(controls_cpp)}}}"
            )

        emitted_weather = "std::nullopt"
        if "weather" in zone:
            weather = require_object(zone["weather"], f"{context}.weather")
            require_keys(weather, {"precipitation", "alerts"}, set(), f"{context}.weather")
            weather_values = []
            for field, cpp_field in (("precipitation", "precip"), ("alerts", "alerts")):
                selections = require_list(weather[field], f"{context}.weather.{field}")
                values = []
                for selection_index, selection in enumerate(selections):
                    roles = expand_selection(selection, by_name, f"{context}.weather.{field}[{selection_index}]")
                    for role in roles:
                        group_name = role.rstrip("ABCDEFGHIJKLMNOPQRSTUVWXYZ")
                        if by_name[group_name]["kind"] != "color-bulb" or role not in zone_roles:
                            raise DocumentError(f"{context}.weather.{field} must target a color light in this zone")
                    values.append(quoted(selection))
                weather_values.append(f".{cpp_field} = {{{', '.join(values)}}}")
            emitted_weather = f"Weather{{{', '.join(weather_values)}}}"

        gate = emit_gate(zone["gate"], f"{context}.gate")
        parts = [
            f".name = {quoted(name)}",
            f".lights = {{{', '.join(emitted_lights)}}}",
            f".gate = {gate}",
            f".modes = {{{emitted_modes}}}",
        ]
        if emitted_controls:
            parts.append(f".controls = {{{', '.join(emitted_controls)}}}")
        if "weather" in zone:
            parts.append(f".weather = {emitted_weather}")
        generated_zones.append("ZoneSpec{" + ", ".join(parts) + "}")

    all_lights = {
        role
        for group_name, group in by_name.items()
        if group["kind"] != "button"
        for role in (
            [f"{group_name}{chr(ord('A') + index)}" for index in range(group["count"])]
            if group["count"] > 1
            else [group_name]
        )
    }
    missing = all_lights - used_roles
    if missing:
        raise DocumentError(f"lights missing from zones: {', '.join(sorted(missing))}")
    return generated_groups, generated_zones


def write_or_check(path: Path, content: str, check: bool) -> bool:
    if check:
        if not path.exists() or path.read_text() != content:
            print(f"generated file is stale: {path.relative_to(ROOT)}", file=sys.stderr)
            return False
        return True
    path.write_text(content)
    print(f"wrote {path.relative_to(ROOT)}")
    return True


def render_array(name: str, values: list[str]) -> str:
    items = ",\n    ".join(values)
    return f"{HEADER}inline constexpr std::array k{name}{{\n    {items}\n}};\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated tables are stale")
    arguments = parser.parse_args()
    try:
        document = json.loads(DOCUMENT.read_text())
        groups, zones = validate_document(document)
        outputs = (
            (LAYOUT_OUTPUT, render_array("Layout", groups)),
            (INSTALLATION_OUTPUT, render_array("Zones", zones)),
        )
        if not all(write_or_check(path, content, arguments.check) for path, content in outputs):
            return 1
    except (OSError, json.JSONDecodeError, DocumentError) as error:
        print(f"installation document: {error}", file=sys.stderr)
        return 1
    if arguments.check:
        print("installation document and generated tables are in sync")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
